import '@testing-library/jest-dom';

// jsdom does not implement matchMedia; LoginPage reads it to resolve the
// system theme, so every test that renders it needs this in place.
if (!window.matchMedia) {
  window.matchMedia = (query: string): MediaQueryList =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList;
}
